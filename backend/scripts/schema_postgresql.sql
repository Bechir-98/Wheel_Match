-- Wheel Match — PostgreSQL schema + optional seed data
-- Usage (from PowerShell / cmd):
--   psql -U postgres -d wheel -f backend/scripts/schema_postgresql.sql
-- Or create DB first:
--   createdb -U postgres wheel
--   psql -U postgres -d wheel -f backend/scripts/schema_postgresql.sql

BEGIN;

-- ---------------------------------------------------------------------------
-- Tear down (reverse dependency order)
-- ---------------------------------------------------------------------------
DROP TABLE IF EXISTS "DEMANDE_FAUTEUIL" CASCADE;
DROP TABLE IF EXISTS "PATIENT_MEDICAL" CASCADE;
DROP TABLE IF EXISTS "USER_PREFERENCES" CASCADE;
DROP TABLE IF EXISTS "CONSULTATION" CASCADE;
DROP TABLE IF EXISTS "EST_ASSOCIE" CASCADE;
DROP TABLE IF EXISTS "COMPOSER_DE" CASCADE;
DROP TABLE IF EXISTS "AVOIR__OPTION" CASCADE;
DROP TABLE IF EXISTS "FAUTEUIL" CASCADE;
DROP TABLE IF EXISTS "PATIENT" CASCADE;
DROP TABLE IF EXISTS "COMERCANT" CASCADE;
DROP TABLE IF EXISTS "UTILISATEUR" CASCADE;
DROP TABLE IF EXISTS "TYPE_FAUTEUIL" CASCADE;
DROP TABLE IF EXISTS "PATHOLOGIE" CASCADE;
DROP TABLE IF EXISTS "MORPHOLOGIE" CASCADE;
DROP TABLE IF EXISTS "COMPOSANT" CASCADE;
DROP TABLE IF EXISTS "OPTION" CASCADE;

-- ---------------------------------------------------------------------------
-- Core tables
-- ---------------------------------------------------------------------------
CREATE TABLE "UTILISATEUR" (
    "ID_UTILISATUER" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ADRESSE" VARCHAR(255),
    "EMAIL" VARCHAR(255) NOT NULL UNIQUE,
    "PASSWORD" VARCHAR(255) NOT NULL,
    "NUMTEL" VARCHAR(32)
);

CREATE TABLE "TYPE_FAUTEUIL" (
    "ID_TYPE" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "NOM_TYPE" VARCHAR(128)
);

CREATE TABLE "PATHOLOGIE" (
    "ID_PATHOLOGIE" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "NOM_PAT" VARCHAR(128),
    "DESCRIPTION" TEXT
);

CREATE TABLE "MORPHOLOGIE" (
    "NOM_ORG" VARCHAR(128) PRIMARY KEY,
    "TAILLEO" NUMERIC(8, 3)
);

CREATE TABLE "COMPOSANT" (
    "ID_COMPOSANT" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "NOM_COMP" VARCHAR(128),
    "TAILLE_COMP" NUMERIC(8, 3)
);

-- "OPTION" is quoted (reserved word)
CREATE TABLE "OPTION" (
    "ID_OPTION" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "NOM_OPTION" VARCHAR(128),
    "TAILLE_OPTION" INTEGER
);

CREATE TABLE "PATIENT" (
    "ID_UTILISATUER" INTEGER PRIMARY KEY REFERENCES "UTILISATEUR" ("ID_UTILISATUER") ON DELETE CASCADE,
    "NOMP" VARCHAR(64) NOT NULL,
    "PRENOMP" VARCHAR(64) NOT NULL,
    "NSS" VARCHAR(64) NOT NULL,
    "POIDS" NUMERIC(6, 2) NOT NULL,
    "TAILLE" NUMERIC(6, 3) NOT NULL,
    "UTILISATION_PRPL" VARCHAR(32) NOT NULL,
    "AIDANT" INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE "COMERCANT" (
    "ID_UTILISATUER" INTEGER PRIMARY KEY REFERENCES "UTILISATEUR" ("ID_UTILISATUER") ON DELETE CASCADE,
    "NOM_COMMERCIAL" VARCHAR(128) NOT NULL
);

CREATE TABLE "FAUTEUIL" (
    "ID_FAUTEUIL" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ID_TYPE" INTEGER NOT NULL REFERENCES "TYPE_FAUTEUIL" ("ID_TYPE"),
    "ID_UTILISATUER" INTEGER NOT NULL REFERENCES "UTILISATEUR" ("ID_UTILISATUER"),
    "PROPULTION" INTEGER NOT NULL,
    "PRIX" NUMERIC(10, 2) NOT NULL,
    "QT_STOCK" INTEGER NOT NULL,
    "IMAGE" VARCHAR(512)
);

CREATE TABLE "AVOIR__OPTION" (
    "ID_FAUTEUIL" INTEGER NOT NULL REFERENCES "FAUTEUIL" ("ID_FAUTEUIL") ON DELETE CASCADE,
    "ID_OPTION" INTEGER NOT NULL REFERENCES "OPTION" ("ID_OPTION") ON DELETE CASCADE,
    PRIMARY KEY ("ID_FAUTEUIL", "ID_OPTION")
);

CREATE TABLE "COMPOSER_DE" (
    "ID_FAUTEUIL" INTEGER NOT NULL REFERENCES "FAUTEUIL" ("ID_FAUTEUIL") ON DELETE CASCADE,
    "ID_COMPOSANT" INTEGER NOT NULL REFERENCES "COMPOSANT" ("ID_COMPOSANT") ON DELETE CASCADE,
    PRIMARY KEY ("ID_FAUTEUIL", "ID_COMPOSANT")
);

CREATE TABLE "EST_ASSOCIE" (
    "ID_PATHOLOGIE" INTEGER NOT NULL REFERENCES "PATHOLOGIE" ("ID_PATHOLOGIE") ON DELETE CASCADE,
    "ID_FAUTEUIL" INTEGER NOT NULL REFERENCES "FAUTEUIL" ("ID_FAUTEUIL") ON DELETE CASCADE,
    PRIMARY KEY ("ID_PATHOLOGIE", "ID_FAUTEUIL")
);

CREATE TABLE "CONSULTATION" (
    "NUM_CONSULTATION" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ID_PATHOLOGIE" INTEGER NOT NULL REFERENCES "PATHOLOGIE" ("ID_PATHOLOGIE"),
    "NOM_ORG" VARCHAR(128) NOT NULL,
    "ID_UTILISATUER" INTEGER NOT NULL REFERENCES "UTILISATEUR" ("ID_UTILISATUER"),
    "PAT_ID_UTILISATUER" INTEGER NOT NULL,
    "DATE_CONSULTATION" DATE NOT NULL
);

CREATE TABLE "USER_PREFERENCES" (
    "ID_UTILISATUER" INTEGER PRIMARY KEY REFERENCES "UTILISATEUR" ("ID_UTILISATUER") ON DELETE CASCADE,
    "PREFS_JSON" TEXT NOT NULL DEFAULT '{}',
    "UPDATED_AT" TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "PATIENT_MEDICAL" (
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PAT_ID_UTILISATUER" INTEGER NOT NULL REFERENCES "UTILISATEUR" ("ID_UTILISATUER") ON DELETE CASCADE,
    "MORPHOLOGIE" VARCHAR(255),
    "PATHOLOGIE" VARCHAR(255),
    "NOTES" TEXT,
    "SOURCE" VARCHAR(16) NOT NULL DEFAULT 'self',
    "UPDATED_AT" TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX "ix_patient_medical_pat" ON "PATIENT_MEDICAL" ("PAT_ID_UTILISATUER");

CREATE TABLE "DEMANDE_FAUTEUIL" (
    "ID_DEMANDE" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ID_PATIENT" INTEGER NOT NULL REFERENCES "UTILISATEUR" ("ID_UTILISATUER") ON DELETE CASCADE,
    "ID_FAUTEUIL" INTEGER NOT NULL REFERENCES "FAUTEUIL" ("ID_FAUTEUIL") ON DELETE CASCADE,
    "STATUT" VARCHAR(32) NOT NULL DEFAULT 'EN_ATTENTE',
    "NOTES" TEXT,
    "ORIGIN" VARCHAR(16) NOT NULL DEFAULT 'patient',
    "PATIENT_ACCEPT" BOOLEAN,
    "DATE_DEMANDE" TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    "DATE_MAJ" TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

